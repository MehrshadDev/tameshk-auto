<section id="step-1-create" class="scroll-mt-24 space-y-3">
    <h2 class="text-lg font-extrabold text-content-main">۱. ایجاد ورکفلو جدید</h2>
    <p class="text-content-muted">
        وارد پنل کاربری شوید و در صفحه <strong class="text-content-main">«ورکفلوها»</strong> روی دکمه <strong class="text-primary">«ورکفلو جدید»</strong> کلیک کنید تا محیط ویرایشگر باز شود. در بالای صفحه می‌توانید با کلیک روی عنوان ورکفلو، نام آن را تغییر دهید.
    </p>
</section>

<section id="step-2-trigger" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">۲. افزودن شروع‌کننده چت (On Chat Message)</h2>
    <p class="text-content-muted">
        در گوشه بالا سمت راست بوم، روی دکمه <strong class="text-primary">+</strong> کلیک کنید، وارد بخش <strong class="text-content-main">«شروع‌کننده‌ها»</strong> شوید و نود <strong class="text-content-main">On Chat Message</strong> را انتخاب کنید. این نود یک درگاه گفتگوی تعاملی به ورکفلو اضافه می‌کند.
    </p>
</section>

<section id="step-3-agent" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">۳. اتصال ایجنت و مدل هوش مصنوعی</h2>
    <ol class="list-decimal space-y-2.5 pr-5 text-content-muted">
        <li>
            روی علامت <strong class="text-content-main">+</strong> کنار نود شروع‌کننده چت کلیک کنید و از بخش <strong class="text-content-main">«هوش مصنوعی»</strong>، نود <strong class="text-purple-500">AI Agent</strong> را اضافه کنید.
        </li>
        <li>
            در پایین نود AI Agent سه ورودی می‌بینید: <code>Chat Model*</code>، <code>Memory</code> و <code>Tool</code>.
        </li>
        <li>
            روی دکمه <strong>+</strong> زیر ورودی <code>Chat Model*</code> کلیک کنید و یکی از مدل‌ها (مثلا <strong>Google Gemini</strong>، <strong>OpenAI</strong> یا <strong>OpenRouter</strong>) را انتخاب نمایید.
        </li>
        <li>
            روی نود مدل دوبار کلیک کنید، از بخش اعتبارنامه کلید API خود را ثبت کنید و سپس مدل دلخواه را از لیست انتخاب نمایید.
        </li>
        <li>
            در صورت تمایل، روی ورودی <code>Memory</code> کلیک کرده و نود <strong>Simple Memory</strong> را وصل کنید تا ایجنت پیام‌های قبلی کاربر را به یاد داشته باشد.
        </li>
    </ol>
</section>

<section id="step-4-test" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">۴. تست زنده در محیط گفتگو</h2>
    <p class="text-content-muted">
        در پایین سمت چپ بوم، روی آیکون سبز رنگ <strong class="text-emerald-500">گفتگو</strong> کلیک کنید تا پنجره چت تستی باز شود. یک پیام بفرستید تا مسیر اجرای نودها را به صورت زنده روی بوم ببینید و پاسخ هوش مصنوعی را دریافت کنید.
    </p>
    <x-docs.callout type="success" title="میانبر ذخیره سریع">
        در هر زمان با کلیدهای ترکیبی <code>Ctrl + S</code> می‌توانید تغییرات ورکفلو را ذخیره کنید.
    </x-docs.callout>
</section>

<section id="step-5-publish" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">۵. انتشار و دریافت لینک عمومی</h2>
    <p class="text-content-muted">
        حالا روی دکمه <strong class="text-primary">«انتشار»</strong> در بالای صفحه کلیک کنید. پس از انتشار، با باز کردن تنظیمات نود <code>On Chat Message</code> می‌توانید <strong class="text-content-main">«آدرس چت عمومی»</strong> را کپی کرده و با دیگران به اشتراک بگذارید.
    </p>
</section>
