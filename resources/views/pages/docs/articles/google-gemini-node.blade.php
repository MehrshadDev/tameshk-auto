<section id="gemini-overview" class="scroll-mt-24 space-y-3">
    <h2 class="text-lg font-extrabold text-content-main">امکانات نود اختصاصی Google Gemini</h2>
    <p class="text-content-muted">
        علاوه بر مدل چت Gemini که به ایجنت متصل می‌شود، تمشک یک نود عملیاتی کامل به نام <strong class="text-blue-500">Google Gemini</strong> در بخش هوش مصنوعی دارد که تمام قابلیت‌های چندوجهی (Multimodal) گوگل را پوشش می‌دهد.
    </p>
</section>

<section id="image-and-audio" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">تولید و تحلیل تصویر و فایل صوتی</h2>
    <ul class="list-disc space-y-2 pr-5 text-content-muted">
        <li>
            <strong class="text-content-main">بخش Image (تصویر):</strong> شامل تحلیل و استخراج اطلاعات از تصویر (<code>Analyze an Image</code>) و همچنین ساخت تصویر با کیفیت بالا از روی متن با مدل <strong>Imagen 3</strong> (<code>Generate an Image</code>) با قابلیت تعیین نسبت ابعاد (<code>1:1</code>، <code>16:9</code>، <code>9:16</code> و...).
        </li>
        <li>
            <strong class="text-content-main">بخش Audio (صدا و رونوشت):</strong> تحلیل فایل‌های صوتی یا تبدیل دقیق گفتار به متن (<code>Transcribe a Recording</code>) با پشتیبانی از فرمت‌های MP3, WAV, OGG, AAC و M4A.
        </li>
    </ul>
</section>

<section id="document-and-video" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">تحلیل اسناد PDF و ویدیو</h2>
    <ul class="list-disc space-y-2 pr-5 text-content-muted">
        <li>
            <strong class="text-content-main">بخش Document (اسناد):</strong> دریافت لینک یا داده Base64 فایل‌های PDF، CSV، HTML و متن ساده و خلاصه‌سازی یا پاسخ به سوالات بر اساس محتوای سند.
        </li>
        <li>
            <strong class="text-content-main">بخش Video و Media File:</strong> تحلیل فریم‌های ویدیو، تولید سناریو و استوری‌بورد ویدیویی و آپلود فایل‌های حجیم در <code>Google Files API</code> برای استفاده در مراحل بعدی.
        </li>
    </ul>
</section>

<section id="file-search-corpus" class="scroll-mt-24 space-y-3 pt-4">
    <h2 class="text-lg font-extrabold text-content-main">مخزن جستجوی فایل (File Search Store)</h2>
    <p class="text-content-muted">
        از طریق بخش <code>File Search</code> می‌توانید در حساب گوگل خود مخازن دانش معنایی (Corpus) بسازید، متون و مستندات کسب‌وکارتان را داخل آن ایندکس کنید و فهرست مخازن خود را مدیریت نمایید.
    </p>
</section>
